"""
Build the item database from the Slice and Dice tier list xlsx.

Output:
  data/items_tierlist.json   full item records (name, tier, description, grade, rank, notes, unlock)
  js/data/items.js           ITEMS_DB used by the web app (name, tier, description, notes)

Usage: python scripts/build_items.py [--check]
  --check  only report whether the outputs are up to date (exit code 1 if not)
"""
import json
import os
import sys

import openpyxl

# Run relative to the repo root regardless of the caller's cwd
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

XLSX = 'guides/Slice and Dice 3.1 Unfair Tier list.xlsx'
SHEET = 'Items Tier 1-9 3.1 '
FIRST_ROW = 9  # row 8 is the header: Item, Tier, Icon, Effect, Tier(grade), Unlock condition, Tier Help, Notes

JSON_OUT = 'data/items_tierlist.json'
JS_OUT = 'js/data/items.js'
JS_HEADER = (
    "// Item database: name, base tier, description and notes for every item.\n"
    "// Generated by scripts/build_items.py from guides/Slice and Dice 3.1 Unfair Tier list.xlsx - do not edit by hand.\n"
)


def clean(value):
    """Cell value as a trimmed string with Unix line endings ('' for empty cells)."""
    if value is None:
        return ''
    return str(value).replace('\r\n', '\n').strip()


def as_int(value):
    try:
        return int(float(value))
    except (TypeError, ValueError):
        return 0


def read_items():
    wb = openpyxl.load_workbook(XLSX, data_only=True)
    ws = wb[SHEET]
    items = []
    for row in ws.iter_rows(min_row=FIRST_ROW, values_only=True):
        name, tier = clean(row[0]), as_int(row[1])
        if not name or tier == 0:
            continue
        items.append({
            'name': name,
            'tier': tier,
            'description': clean(row[3]),
            'grade': clean(row[4]),
            'rank': as_int(row[6]),
            'notes': clean(row[7]),
            'unlock': clean(row[5]),
        })
    return items


def render_json(items):
    return json.dumps(items, indent=2, ensure_ascii=False) + '\n'


def render_js(items):
    rows = [
        '    ' + json.dumps({k: item[k] for k in ('name', 'tier', 'description', 'notes')},
                            ensure_ascii=False, separators=(',', ':'))
        for item in items
    ]
    return JS_HEADER + 'const ITEMS_DB = [\n' + ',\n'.join(rows) + '\n];\n'


def main():
    items = read_items()
    outputs = {JSON_OUT: render_json(items), JS_OUT: render_js(items)}

    if '--check' in sys.argv:
        stale = []
        for path, content in outputs.items():
            with open(path, encoding='utf-8') as f:
                if f.read().replace('\r\n', '\n') != content:
                    stale.append(path)
        print('Out of date: ' + ', '.join(stale) if stale else 'Up to date')
        sys.exit(1 if stale else 0)

    for path, content in outputs.items():
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(content)
        print(f'Wrote {path}')
    print(f'{len(items)} items')


if __name__ == '__main__':
    main()
